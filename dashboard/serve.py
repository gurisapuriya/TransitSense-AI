"""Loopback operator service. Serves only aggregate measurements and dashboard assets."""
import argparse
import json
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit

BASE = Path(__file__).resolve().parent
RUNS = {"controlled": "Controlled stop · simulation", "boarding": "Doorway · boarding video",
        "doorway": "Doorway · mixed flow video", "bag": "Aisle · composite bag trial",
        "front_row": "Cabin · February still", "quiet": "Cabin · quiet still", "moderate": "Cabin · moderate still", "busy": "Cabin · busy still"}


def handler_for(live, extra=None):
    runs = {key: (name, BASE / "replays" / (key + ".json")) for key, name in RUNS.items()}
    if extra:
        runs["local"] = ("Local recording", extra)

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            path = urlsplit(self.path).path
            try:
                if path == "/api/runs":
                    self.json_response([{"id": k, "name": v[0]} for k,v in runs.items()])
                elif path == "/api/live":
                    if not live.is_file():
                        self.json_response({"status": "offline", "sample": None})
                        return
                    state = json.loads(live.read_bytes())
                    if state["status"] in ("running", "starting") and time.time() - state["updated"] > 5:
                        state.update(status="stale", sample=None)
                    self.json_response(state)
                elif path.startswith("/api/runs/") and path[10:] in runs:
                    self.send_bytes(runs[path[10:]][1].read_bytes(), "application/json")
                elif path in ("/", "/app.js", "/style.css"):
                    name, mime = {"/": ("index.html", "text/html"), "/app.js": ("app.js","text/javascript"),
                                  "/style.css": ("style.css","text/css")}[path]
                    self.send_bytes((BASE / "static" / name).read_bytes(), mime + "; charset=utf-8")
                else:
                    self.send_error(404)
            except (OSError, ValueError, KeyError):
                self.send_error(503, "Measurement source unavailable")

        def log_message(self, fmt, *args):
            if str(args[1]) != "200":
                super().log_message(fmt, *args)

        def json_response(self, data):
            self.send_bytes(json.dumps(data, allow_nan=False).encode(), "application/json")

        def send_bytes(self, data, mime):
            self.send_response(200)
            self.send_header("Content-Type", mime)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.end_headers()
            self.wfile.write(data)

    return Handler


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--port", type=int, default=8765)
    p.add_argument("--state", type=Path, default=BASE.parent / "results/monitor/live.json")
    p.add_argument("--replay", type=Path, help="Additional aggregate replay generated by inference.monitor")
    args = p.parse_args()
    if args.replay and not args.replay.is_file():
        p.error("Replay file does not exist")
    with ThreadingHTTPServer(("127.0.0.1", args.port), handler_for(args.state, args.replay)) as server:
        print(f"TransitSense operator display: http://127.0.0.1:{server.server_port}/", flush=True)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass


if __name__ == "__main__":
    main()
