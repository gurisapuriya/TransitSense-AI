"""Loopback operator service. Serves only aggregate measurements and dashboard assets."""
import argparse
import os
from importlib.util import find_spec
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit

from .data import BASE, DEFAULT_STATE, api_data, replays


def handler_for(live, extra=None):
    runs = replays(extra)

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            path = urlsplit(self.path).path
            try:
                if path.startswith("/api/"):
                    self.send_bytes(api_data(path, live, runs), "application/json")
                elif path in ("/", "/app.js", "/style.css"):
                    name, mime = {"/": ("index.html", "text/html"), "/app.js": ("app.js","text/javascript"),
                                  "/style.css": ("style.css","text/css")}[path]
                    self.send_bytes((BASE / "static" / name).read_bytes(), mime + "; charset=utf-8")
                else:
                    self.send_error(404)
            except KeyError:
                self.send_error(503, "Invalid measurement source")
            except LookupError:
                self.send_error(404)
            except (OSError, ValueError):
                self.send_error(503, "Measurement source unavailable")

        def log_message(self, fmt, *args):
            if str(args[1]) != "200":
                super().log_message(fmt, *args)

        def send_bytes(self, data, mime):
            self.send_response(200)
            self.send_header("Content-Type", mime)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.end_headers()
            self.wfile.write(data)

    return Handler


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--port", type=int, default=8765)
    p.add_argument("--state", type=Path, default=DEFAULT_STATE)
    p.add_argument("--replay", type=Path, help="Additional aggregate replay generated by inference.monitor")
    p.add_argument("--basic", action="store_true", help="Use the standard-library console")
    args = p.parse_args()
    if args.replay and not args.replay.is_file():
        p.error("Replay file does not exist")
    if not args.basic and find_spec("streamlit") is not None:
        import streamlit as st
        import uvicorn
        from starlette.responses import Response
        from starlette.routing import Route

        sources = replays(args.replay)

        def api(request):
            try:
                body = api_data(request.url.path, args.state, sources)
            except KeyError:
                return Response(status_code=503)
            except LookupError:
                return Response(status_code=404)
            except (ValueError, OSError):
                return Response(status_code=503)
            return Response(body, media_type="application/json", headers={"Cache-Control": "no-store"})

        os.environ["TRANSITSENSE_STATE"] = str(args.state.resolve())
        os.environ["TRANSITSENSE_REPLAY"] = str(args.replay.resolve()) if args.replay else ""
        app = st.App(BASE / "console.py", routes=[Route("/api/{path:path}", api)])
        uvicorn.run(app, host="127.0.0.1", port=args.port, access_log=False)
        return
    with ThreadingHTTPServer(("127.0.0.1", args.port), handler_for(args.state, args.replay)) as server:
        print(f"TransitSense operator display: http://127.0.0.1:{server.server_port}/", flush=True)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass


if __name__ == "__main__":
    main()
